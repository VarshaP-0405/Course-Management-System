function validationError(message) {
  const error = new Error(message)
  error.statusCode = 400
  return error
}

export function requireObjectBody(body) {
  if (!body || typeof body !== 'object' || Array.isArray(body)) {
    throw validationError('Request body must be a JSON object.')
  }
  return body
}

function isValidValue(type, value) {
  switch (type) {
    case 'string':
      return typeof value === 'string' && value.length <= 5000
    case 'email':
      return typeof value === 'string' && value.length <= 254 && emailPattern.test(value.trim())
    case 'password':
      return typeof value === 'string' && value.length >= 6 && value.length <= 128
    case 'role':
      return ['1', '2', '3'].includes(String(value))
    case 'number':
      return positiveNumber(value)
    case 'nonNegativeNumber':
      return nonNegativeNumber(value)
    case 'percentage':
      return nonNegativeNumber(value) && Number(value) <= 100
    case 'rating':
      return Number.isInteger(Number(value)) && Number(value) >= 1 && Number(value) <= 5
    case 'boolean':
      return typeof value === 'boolean'
    case 'status':
      return ['Y', 'N', true, false].includes(value)
    case 'url':
      if (typeof value !== 'string' || value.length > 2048) return false
      try {
        const url = new URL(value)
        return url.protocol === 'http:' || url.protocol === 'https:'
      } catch {
        return false
      }
    default:
      return false
  }
}

export function validateRecord(collection, body, { partial = false } = {}) {
  requireObjectBody(body)
  if (partial && Object.keys(body).length === 0) {
    throw validationError('At least one field is required.')
  }
  const rules = fields[collection]
  if (!rules) {
    const error = new Error(`Unknown collection: ${collection}`)
    error.statusCode = 404
    throw error
  }

  if (Object.hasOwn(body, 'id')) {
    throw validationError('The id field is generated by the server and cannot be changed.')
  }

  if (!partial) {
    for (const name of requiredFields[collection]) {
        if (body[name] === undefined || body[name] === null
          || (typeof body[name] === 'string' && !body[name].trim())) {
          throw validationError(`${name} is required.`)
        }
      }
    }

    for (const [name, value] of Object.entries(body)) {
      if (!Object.hasOwn(rules, name)) {
        throw validationError(`Unknown field: ${name}.`)
      }
      if (value === null && !requiredFields[collection].includes(name)) continue
      if (!isValidValue(rules[name], value)) {
        throw validationError(`${name} is invalid.`)
      }
    }

  return body
}

export function validateRegistration(body) {
  requireObjectBody(body)
  validateRecord('users', {
    email: body.email,
    password: body.password,
    role: 3,
  })

  for (const name of ['first_name', 'last_name']) {
    if (typeof body[name] !== 'string' || !body[name].trim() || body[name].length > 120) {
      throw validationError(`${name} is required and must be 120 characters or fewer.`)
    }
  }
  for (const name of ['phone', 'department']) {
    if (body[name] !== undefined && (typeof body[name] !== 'string' || body[name].length > 120)) {
      throw validationError(`${name} must be a string of 120 characters or fewer.`)
    }
  }
  return body
}

export function validateLogin(body) {
  requireObjectBody(body)
  if (typeof body.email !== 'string' || !emailPattern.test(body.email.trim())) {
    throw validationError('A valid email is required.')
  }
  if (typeof body.password !== 'string' || !body.password) {
    throw validationError('Password is required.')
  }
  if (body.role !== undefined && !['1', '2', '3'].includes(String(body.role))) {
    throw validationError('Role must be 1 (admin), 2 (faculty), or 3 (student).')
  }
}
